"""Per-family tau_veto calibration from each family's own structure.

Owner directive: calibrate the per-family tau_veto with high-level data
sources.

THE PROBLEM, measured in this repository
The Sagnac gate vetoes a candidate wave when its phase divergence from a
reference boundary (axiom) exceeds `tau_veto`. The spec pins ONE number,
`tau_veto = 0.0431`. The repo measured that two natural statistics
diverge off unit modulus:

    spec form   1 - mean_d cos(dtheta_d)
    normed form 1 - Re<p,a> / (|p| |a|)

They agree EXACTLY on unit-modulus waves (0.000e+00) and diverge on
Stiefel rows (5.61e-02 at D=1024) by MORE than tau itself. So the veto
DECISION depends on which form an implementer chose.

WHAT "HIGH-LEVEL DATA SOURCES" MEANS HERE, stated precisely
Not a downloaded corpus. The families this repository actually produces,
each built through its PRODUCTION code path:
  1. qfhrr_category - phase-ring tokens sharing a category phasor
  2. sensor         - real image crop waves (one group per real image)
  3. stiefel        - Stiefel-retracted codebook rows
  4. learned        - DeltaMemory recalled rows
  5. gaussian       - synthetic control, must NOT be separable

THE DISCRIMINATING DESIGN
A veto must ACCEPT related waves and REJECT unrelated ones. So each
family is built as GROUPS, and two delta distributions are measured on
the SAME vector space:
  WITHIN : pairs inside one group (related)
  ACROSS : pairs in different groups (unrelated)
The separating band is [max(WITHIN), min(ACROSS)]. tau must sit inside.
A family whose rows are mutually orthogonal has WITHIN ~ ACROSS, an
EMPTY band, and CANNOT be calibrated by any threshold. That is a
reported outcome, not a failure. It is the expected result for the
deliberately-decorrelated families (stiefel, learned, gaussian).

PRE-REGISTERED DECISION RULE, fixed before the first run
- separable(F) : max(WITHIN_F) < min(ACROSS_F).
- tau_rec(F)   : geometric midpoint of the band when separable, else None.
- form_divergence(F): max |spec form - normed form| over every measured
  pair. When it exceeds tau, the family needs a PINNED STATISTIC FORM,
  not merely its own tau. That distinction is the point of the probe.
- CONTROL: `gaussian` must come out NOT separable. If it is separable,
  the design measures something other than structure and the run is VOID.

ALL FAMILIES ARE THE SAME LENGTH. Guarded by assertion, because a
length mismatch between families would silently corrupt every metric.

DISCLOSURE. The sensor family uses real image bytes on this host. Other
families are generated by production code over generated data. No task
is attempted or solved. No capability claim.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from henri.config import WaveConfig
from henri.gram import stiefel_retract
from henri.memory import DeltaMemory
from henri.state import WaveState

TAU_SPEC = 0.0431
FULL_DIM = 65536


def unit(v: np.ndarray) -> np.ndarray:
    n = np.linalg.norm(v)
    if n <= 0 or not np.isfinite(n):
        raise ValueError("zero or non-finite vector")
    return v / n


def form_spec(psi: np.ndarray, axiom: np.ndarray) -> float:
    """1 - mean_d cos(angle(psi_d * conj(axiom_d)))."""
    return float(1.0 - np.mean(np.cos(np.angle(psi * np.conj(axiom)))))


def form_normed(psi: np.ndarray, axiom: np.ndarray) -> float:
    """1 - Re<psi, axiom> / (|psi| |axiom|)."""
    np_, na = np.linalg.norm(psi), np.linalg.norm(axiom)
    return float(1.0 - np.real(np.vdot(psi, axiom)) / (np_ * na))


