def build_families(dim: int, rng, per_group: int = 6):
    """Every family at exactly L = cfg.slot_span, production paths only.

    `WaveConfig(dim=D)` has `slot_span = D // 4`. The families that fill a
    SINGLE slot (qFHRR tokens, sensor crops) are slot length. So every
    family is built at `L = cfg.slot_span` and one assertion checks the
    same `L` across families.

    This replaces a version that mixed `cfg.dim` with `cfg.slot_span` and
    raised `ValueError: expected length 256, got 1024` at `--dim 1024`.
    """
    cfg = WaveConfig(dim=int(dim))
    L = int(cfg.slot_span)
    fams: dict = {}

    # 1. qfhrr categorical: tokens sharing a category phasor
    try:
        from henri.qfhrr_tokenizer import QFHRRTokenizer
        tok = QFHRRTokenizer(cfg)
        groups = []
        for c in range(4):
            g = []
            for i in range(per_group):
                q = tok.encode_token(category_id=c, semantic_id=i,
                                     instance_id=c * per_group + i)
                g.append(unit(np.asarray(tok.to_complex_phasor(q)).ravel()))
            groups.append(np.stack(g))
        fams["qfhrr_category"] = {"groups": groups}
    except Exception as exc:
        fams["qfhrr_category"] = {"error": f"{type(exc).__name__}: {exc}"}

    # 1b. qfhrr FAMILY path. This is the spec's "Structured Semantic Engram
    # Solution", which claims to defeat the Random-Ring Orthogonal Isolation
    # Trap by sharing a categorical baseplate across a family. The PLAIN
    # `encode_token` path above measured NOT separable at slot length, so the
    # structured path is the one that decides whether a calibration exists.
    try:
        from henri.qfhrr_tokenizer import QFHRRTokenizer
        tok = QFHRRTokenizer(cfg)
        groups = []
        for f in range(4):
            g = []
            for m in range(per_group):
                q = tok.encode_family_token(family_id=f, member_id=m)
                arr = np.asarray(q)
                v = (np.asarray(tok.to_complex_phasor(arr)).ravel()
                     if arr.dtype.kind in "iu" else arr.ravel())
                g.append(unit(v))
            groups.append(np.stack(g))
        fams["qfhrr_family"] = {"groups": groups}
    except Exception as exc:
        fams["qfhrr_family"] = {"error": f"{type(exc).__name__}: {exc}"}

    # 2. sensor: real image crops, one group per real image
    paths = _image_paths(limit=5)
    try:
        from PIL import Image
        from henri.sensor_ingress import to_gray_float
        from henri.spatial_encoder import ContinuousSpatialEncoder
        groups, skipped = [], []
        for p in paths:
            try:
                img = np.asarray(Image.open(p).convert("RGB"))
            except Exception as exc:
                skipped.append({"path": Path(str(p)).name,
                                "error": type(exc).__name__})
                continue
            field = to_gray_float(img)
            h, w = field.shape
            if h < 32 or w < 32:
                skipped.append({"path": Path(str(p)).name,
                                "error": f"too small {h}x{w}"})
                continue
            g = []
            for i in range(per_group):
                r0 = int((i * max(1, h - 32)) / max(1, per_group - 1))
                c0 = int((i * max(1, w - 32)) / max(1, per_group - 1))
                crop = field[r0:r0 + 32, c0:c0 + 32]
                enc = ContinuousSpatialEncoder(cfg, seed=900 + i)
                g.append(unit(np.asarray(enc.encode_2d_field(crop)).ravel()))
            groups.append(np.stack(g))
        if len(groups) >= 2:
            fams["sensor_image"] = {"groups": groups,
                                    "n_images": len(groups),
                                    "skipped_images": skipped,
                                    "source": "real image bytes"}
        else:
            fams["sensor_image"] = {
                "error": f"need >=2 usable real images, got {len(groups)}",
                "skipped_images": skipped}
    except Exception as exc:
        fams["sensor_image"] = {"error": f"{type(exc).__name__}: {exc}"}

    # 3. stiefel: deliberately decorrelated codebook rows
    A = stiefel_retract(rng.standard_normal((per_group, L))
                        + 1j * rng.standard_normal((per_group, L)))
    B = stiefel_retract(rng.standard_normal((per_group, L))
                        + 1j * rng.standard_normal((per_group, L)))
    fams["stiefel"] = {"groups": [A, B]}

    # 4. learned: DeltaMemory recalled rows from two memories
    def _learned(rank=64):
        """Production learner: DeltaMemory write then read.

        Keys and values are built at exactly `L`, NOT via
        `WaveState.random(cfg)`, which yields `cfg.dim`. The LEARNER is
        what is under test; the vector source is not.
        """
        mem = DeltaMemory.build(L, rank=rank)
        keys = []
        for _ in range(per_group):
            kk = unit(rng.standard_normal(L) + 1j * rng.standard_normal(L))
            vv = unit(rng.standard_normal(L) + 1j * rng.standard_normal(L))
            mem.write(kk, vv)
            keys.append(kk)
        return np.stack([unit(mem.read(kk)) for kk in keys])

    fams["learned"] = {"groups": [_learned(), _learned()]}

    # 5. gaussian control: must NOT be separable
    g = [np.stack([unit(rng.standard_normal(L)
                        + 1j * rng.standard_normal(L))
                   for _ in range(per_group)]) for _ in range(2)]
    fams["gaussian"] = {"groups": g}

    for name, spec in fams.items():
        if "error" in spec:
            continue
        grp = spec["groups"]
        assert all(x.shape[1] == L for x in grp), \
            f"{name}: family length mismatch, expected {L}"
    return fams, L


def pair_stats(groups, within: bool):
    s1, s2, div = [], [], []
    ng = len(groups)
    for i in range(ng):
        for j in range(ng):
            if (within and i != j) or (not within and i == j):
                continue
            A, B = groups[i], groups[j]
            for x in range(A.shape[0]):
                for y in range(B.shape[0]):
                    if within and x == y:
                        continue
                    f1 = form_spec(A[x], B[y])
                    f2 = form_normed(A[x], B[y])
                    s1.append(f1)
                    s2.append(f2)
                    div.append(abs(f1 - f2))
    return s1, s2, div


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dim", type=int, default=FULL_DIM)
    ap.add_argument("--out", type=str,
                    default="receipts/tau_veto_calibration.json")
    a = ap.parse_args()

    t0 = time.perf_counter()
    rng = np.random.default_rng(20261012)
    fams, L = build_families(a.dim, rng)

    rec = {
        "probe": "tau_veto_per_family_calibration",
        "tau_spec": TAU_SPEC,
        "dim": a.dim, "slot_span": L,
        "seed": 20261012,
        "design": ("separating band [max(WITHIN), min(ACROSS)] on the same "
                   "vector space; an orthogonal family has an EMPTY band "
                   "and is not calibratable by any threshold"),
        "decision_rule": "pre-registered in the module docstring",
        "disclosure": ("Sensor family uses real image bytes. Other families "
                       "are production code over generated data. No task "
                       "attempted or solved."),
        "families": {},
    }

    for name, spec in fams.items():
        if "error" in spec:
            rec["families"][name] = {"status": "UNAVAILABLE",
                                     "error": spec["error"]}
            continue
        groups = spec["groups"]
        w1, w2, wd = pair_stats(groups, within=True)
        c1, c2, cd = pair_stats(groups, within=False)
        if not w1 or not c1:
            rec["families"][name] = {"status": "INSUFFICIENT_PAIRS",
                                     "n_within": len(w1),
                                     "n_across": len(c1)}
            continue

        wmax1, wmax2 = max(w1), max(w2)
        cmin1, cmin2 = min(c1), min(c2)
        sep1, sep2 = wmax1 < cmin1, wmax2 < cmin2
        divmax = max(max(wd), max(cd))
        m = {
            "status": "MEASURED",
            "n_groups": len(groups),
            "n_within_pairs": len(w1), "n_across_pairs": len(c1),
            "within_max_spec": wmax1, "across_min_spec": cmin1,
            "within_median_spec": float(np.median(w1)),
            "across_median_spec": float(np.median(c1)),
            "within_max_normed": wmax2, "across_min_normed": cmin2,
            "separable_spec": bool(sep1), "separable_normed": bool(sep2),
            "tau_recommended_spec": (float(np.sqrt(wmax1 * cmin1))
                                     if sep1 else None),
            "tau_recommended_normed": (float(np.sqrt(wmax2 * cmin2))
                                       if sep2 else None),
            "form_divergence_max": divmax,
            "form_divergence_exceeds_tau": bool(divmax > TAU_SPEC),
            "spec_tau_in_band": bool(sep1 and wmax1 < TAU_SPEC < cmin1),
        }
        if "source" in spec:
            m["source"] = spec["source"]
            m["n_images"] = spec["n_images"]
        rec["families"][name] = m

    ctrl = rec["families"].get("gaussian", {})
    ctrl_ok = (ctrl.get("status") == "MEASURED"
               and ctrl.get("separable_spec") is False)
    rec["control"] = {
        "family": "gaussian",
        "expectation": "NOT separable (deliberately decorrelated rows)",
        "observed_separable": ctrl.get("separable_spec"),
        "control_holds": bool(ctrl_ok),
    }
    rec["wall_clock_s"] = time.perf_counter() - t0
    rec["status"] = "COMPLETE" if ctrl_ok else "VOID_CONTROL_FAILED"

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(rec, indent=2, sort_keys=True).encode("utf-8")
    digest = hashlib.sha256(body).hexdigest()
    out.write_bytes(body)
    out.with_suffix(out.suffix + ".sha256").write_bytes(
        (digest + "\n").encode())
    rb = hashlib.sha256(out.read_bytes()).hexdigest()

    print("=== PER-FAMILY tau_veto CALIBRATION ===", file=sys.stderr)
    print(f"dim={a.dim} slot={L} tau_spec={TAU_SPEC}", file=sys.stderr)
    for n, m in rec["families"].items():
        if m.get("status") != "MEASURED":
            print(f"{n:<16} {m.get('status')}  {m.get('error','')}",
                  file=sys.stderr)
            continue
        print("%-16s within_max=%.6f across_min=%.6f sep=%-5s tau_rec=%-9s "
              "fdiv=%.4e%s"
              % (n, m["within_max_spec"], m["across_min_spec"],
                 m["separable_spec"],
                 ("%.6f" % m["tau_recommended_spec"])
                 if m["tau_recommended_spec"] is not None else "NONE",
                 m["form_divergence_max"],
                 "  [>TAU]" if m["form_divergence_exceeds_tau"] else ""),
              file=sys.stderr)
    print(f"control_holds={rec['control']['control_holds']}",
          file=sys.stderr)
    print(f"status={rec['status']} sha256={digest} readback={rb == digest}",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
